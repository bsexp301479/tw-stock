// 整頁 HTML；id = 要標示的名詞代號（組代號、空字串都不標示）
function helpHTML(id) {
  const row = x => `<div class="help-t${x[0] === id ? ' on' : ''}" id="help-${x[0]}"><b>${x[1]}</b><div>${x[2]}${x[4] ? `　<a href="${x[4]}">${x[3]} →</a>` : ''}</div></div>`;
  return '<section class="sec card"><div class="sec-h"><h2>名詞說明</h2></div><div class="muted small">本站各頁用到的名詞與本站的算法；官方或其他網站的定義可能不同。</div>' +
    `<div class="help-g">${HELP.map(g => `<a class="chip" href="#/help/${g[0]}">${g[1]}</a>`).join('')}</div></section>` +
    HELP.map(g => `<section class="sec card" id="help-${g[0]}"><div class="sec-h"><h2>${g[1]}</h2></div>${g[2].map(row).join('')}</section>`).join('') +
    '<div class="muted small">名詞說明只描述算法與定義，不是買賣訊號。</div>';
}

// #/help/代號：畫完整頁後捲到名詞或組（route() 捲到頂端之後）；代號不存在 → 網址改回 #/help、不捲動
window.renderHelp = function (arg) {
  const ids = HELP.reduce((a, g) => a.concat(g[0], g[2].map(x => x[0])), []);
  const id = ids.indexOf(arg) >= 0 ? arg : '';
  if (arg && !id) history.replaceState(history.state, '', '#/help');
  document.getElementById('view').innerHTML = helpHTML(id);
  if (id) requestAnimationFrame(() => { const e = document.getElementById('help-' + id); if (e) e.scrollIntoView(); });   // 已換頁就不捲
};
